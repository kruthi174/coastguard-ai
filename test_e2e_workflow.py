"""
End-to-End Workflow Verification Suite for CoastGuard AI
Tests the complete application lifecycle via direct ASGI in-memory client:
1. System Health Check & Service Discovery
2. Demonstration incidents retrieval (50 records across 9 states)
3. AI DBSCAN Incident Clustering Execution (Haversine distance)
4. Citizen Hazard Report Submission (with automatic NLP duplicate detection)
5. Disaster Management Officer Incident Verification Workflow
6. Explainable Coastal Risk Intelligence Index Calculation
7. Static React Single Page Application (SPA) Serving
"""

import os
import sys
import json
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT_DIR))

from fastapi.testclient import TestClient
from backend.main import app


def test_suite():
    print("\n" + "="*70)
    print(" COASTGUARD AI — END-TO-END WORKFLOW VERIFICATION SUITE")
    print("="*70)

    client = TestClient(app)

    # 1. Health Check
    print("\n[TEST 1] Verifying System Health...")
    res = client.get("/api/health")
    assert res.status_code == 200, f"Expected 200, got {res.status_code}"
    body = res.json()
    assert body["status"] == "Online", "Status not Online"
    print(f"  ✓ API Online: {body['app']} v{body['version']}")

    # 2. Demonstration Dataset Verification
    print("\n[TEST 2] Verifying Demonstration Dataset (50 Incidents)...")
    res = client.get("/api/incidents?limit=100")
    assert res.status_code == 200
    incidents = res.json()["incidents"]
    assert len(incidents) >= 50, f"Expected at least 50 incidents, got {len(incidents)}"
    states = set(inc["state"] for inc in incidents)
    print(f"  ✓ Retrieved {len(incidents)} incidents across {len(states)} coastal states:")
    print(f"    States: {', '.join(sorted(states))}")

    # 3. AI DBSCAN Incident Clustering Execution
    print("\n[TEST 3] Executing Real AI DBSCAN Incident Clustering...")
    cluster_payload = {
        "eps_km": 35.0,
        "min_samples": 2,
        "group_by_hazard": False
    }
    res = client.post("/api/clusters/run-dbscan", json=cluster_payload)
    assert res.status_code == 200
    cl_body = res.json()
    clusters = cl_body["clusters"]
    metrics = cl_body["metrics"]
    assert len(clusters) > 0, "No clusters generated by DBSCAN"
    print(f"  ✓ DBSCAN Algorithm Executed Successfully!")
    print(f"    - Clusters Identified:  {len(clusters)}")
    print(f"    - Incidents Clustered:  {metrics['clustered_count']}")
    print(f"    - Noise Points:         {metrics['noise_count']}")
    print(f"    - Neighborhood Radius:  {metrics['eps_km']} km")
    first_cl = clusters[0]
    print(f"    - Sample Cluster:       {first_cl['cluster_id']} - {first_cl['name']}")
    print(f"      Centroid: ({first_cl['centroid_latitude']}, {first_cl['centroid_longitude']}) | Radius: {first_cl['radius_km']} km")

    # 4. Citizen Hazard Reporting with NLP Duplicate Detection
    print("\n[TEST 4] Testing Citizen Hazard Report Submission & NLP Duplicate Detection...")
    # Report near Dwarka (near CG-2026-0001) to test duplicate corroboration
    new_report = {
        "reporter_name": "Citizen Field Observer",
        "reporter_contact": "+91 99999 88888",
        "hazard_category": "High waves",
        "description": "Massive swells over 4m splashing over Dwarka seawall near temple pathway.",
        "location_name": "Dwarka Coastal Path",
        "state": "Gujarat",
        "latitude": 22.2410,
        "longitude": 68.9690,
        "severity": "High"
    }
    res = client.post("/api/incidents", json=new_report)
    assert res.status_code == 200
    report_body = res.json()
    new_id = report_body["incident_id"]
    dup_flag = report_body.get("duplicate_detection")
    print(f"  ✓ Report Registered with ID: {new_id}")
    if dup_flag and dup_flag.get("is_potential_duplicate"):
        print(f"  ✓ NLP Duplicate Detection Active:")
        print(f"    - Matched Incident: {dup_flag['matched_incident_id']}")
        print(f"    - Match Confidence: {dup_flag['duplicate_confidence_percent']}%")
        print(f"    - Distance:         {dup_flag['distance_km']} km")
    else:
        print("  - Unique incident logged (no duplicates in threshold).")

    # 5. Disaster Management Officer Verification Workflow
    print("\n[TEST 5] Testing Officer Incident Verification & Remarks...")
    verify_payload = {
        "status": "Verified",
        "verification_remarks": "Field patrol corroborated wave inundation at location. Dispatched safety cordons.",
        "verified_by": "Senior Coastal Officer Sharma"
    }
    res = client.patch(f"/api/incidents/{new_id}/status", json=verify_payload)
    assert res.status_code == 200
    assert res.json()["status"] == "Verified"
    print(f"  ✓ Incident {new_id} updated to 'Verified' with officer inspection remarks.")

    # 6. Explainable Coastal Risk Intelligence Engine
    print("\n[TEST 6] Testing Explainable Coastal Risk Scoring (0-100)...")
    res = client.get("/api/risk/zones")
    assert res.status_code == 200
    risk_body = res.json()
    zones = risk_body["zones"]
    assert len(zones) == 9, f"Expected 9 coastal states, got {len(zones)}"
    top_zone = zones[0]
    print(f"  ✓ Generated Risk Indices for {len(zones)} Coastal Maritime Zones:")
    print(f"    - Top Risk Zone: {top_zone['zone_name']}")
    print(f"    - Risk Score:    {top_zone['risk_score']}/100 ({top_zone['risk_level']} Risk)")
    print(f"    - Active Reports:{top_zone['active_incidents']}")
    breakdown = top_zone["breakdown"]
    print(f"    - Transparent Scoring Breakdown:")
    print(f"      ├─ Frequency: {breakdown['frequency_score']['points']}/25 pts ({breakdown['frequency_score']['reason']})")
    print(f"      ├─ Severity:  {breakdown['severity_score']['points']}/30 pts ({breakdown['severity_score']['reason']})")
    print(f"      ├─ Recency:   {breakdown['recency_score']['points']}/20 pts ({breakdown['recency_score']['reason']})")
    print(f"      ├─ Density:   {breakdown['density_score']['points']}/15 pts ({breakdown['density_score']['reason']})")
    print(f"      └─ Evidence:  {breakdown['evidence_score']['points']}/10 pts ({breakdown['evidence_score']['reason']})")

    # 7. Frontend Static Build Delivery
    print("\n[TEST 7] Testing Frontend SPA HTML Delivery...")
    res = client.get("/")
    assert res.status_code == 200
    html = res.text
    assert "<title>COASTGUARD AI" in html
    assert 'id="root"' in html
    print("  ✓ Full React Single Page Application (SPA) served successfully at root '/'")

    print("\n" + "="*70)
    print(" ALL 7 END-TO-END WORKFLOW TESTS PASSED PERFECTLY! [100% SUCCESS]")
    print("="*70 + "\n")


if __name__ == "__main__":
    test_suite()
